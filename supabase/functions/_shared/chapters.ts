export interface Chapter {
  id: string;
  name: string;
}

/** บททั้งหมดของวิชาในระดับนั้น */
export function chaptersOf(level: string, subject: string): Chapter[] {
  return (CHAPTER_NAMES[level]?.[subject] ?? []).map((name, i) => ({ id: `${level}.${subject}.${i + 1}`, name }));
}

/** ชื่อบทจากรหัส (ไม่พบ = null) */
export function chapterName(id: string): string | null {
  const [level, subject, n] = id.split('.');
  return CHAPTER_NAMES[level]?.[subject]?.[Number(n) - 1] ?? null;
}
